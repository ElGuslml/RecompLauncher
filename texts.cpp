uint32_t SystemLanguage() {
  switch (PRIMARYLANGID(GetUserDefaultUILanguage())) {
    case LANG_GERMAN:
      return 3;
    case LANG_FRENCH:
      return 4;
    case LANG_SPANISH:
      return 5;
    case LANG_ITALIAN:
      return 6;
    default:
      return 1;
  }
}

uint32_t TextsLanguage(uint32_t chosen) {
  for (const LauncherLanguage& l : kLauncherLanguages) {
    if (l.id == chosen) return chosen;
  }
  return SystemLanguage();
}

const char* LauncherLanguageName(uint32_t id) {
  for (const LauncherLanguage& l : kLauncherLanguages) {
    if (l.id == id) return l.name;
  }
  return "English";
}

const Texts& TextsFor(uint32_t language) {
  static const Texts kGermanComplete = Complete(kGerman);
  static const Texts kFrenchComplete = Complete(kFrench);
  static const Texts kSpanishComplete = Complete(kSpanish);
  static const Texts kItalianComplete = Complete(kItalian);
  switch (language) {
    case 3:
      return kGermanComplete;
    case 4:
      return kFrenchComplete;
    case 5:
      return kSpanishComplete;
    case 6:
      return kItalianComplete;
    default:
      return kEnglish;
  }
}

